BEGIN;


-- ============================================================================
-- 1. NOTIFICATIONS
-- ============================================================================
-- Creates the notification/message itself.
--
-- One notification may have many recipients.
-- Delivery/read state is stored in notification_recipients.
-- ============================================================================

CREATE TABLE IF NOT EXISTS app.notifications (
    id                  uuid PRIMARY KEY DEFAULT platform.generate_uuid(),

    college_id          uuid,

    notification_type   text NOT NULL,

    title               text NOT NULL,
    message             text NOT NULL,

    priority            text NOT NULL DEFAULT 'NORMAL',

    channel             text NOT NULL DEFAULT 'IN_APP',

    status              text NOT NULL DEFAULT 'QUEUED',

    source_module       text,

    source_record_id    uuid,

    scheduled_at        timestamptz,
    sent_at             timestamptz,

    expires_at          timestamptz,

    created_by          uuid,

    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_notifications_college
        FOREIGN KEY (college_id)
        REFERENCES platform.colleges(college_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_notifications_created_by
        FOREIGN KEY (created_by)
        REFERENCES app.users(user_id)
        ON DELETE SET NULL,

    CONSTRAINT chk_notifications_type
        CHECK (
            notification_type IN (
                'SYSTEM',
                'ANNOUNCEMENT',
                'LEAVE',
                'GATE_PASS',
                'VISITOR',
                'PARCEL',
                'COMPLAINT',
                'SOS',
                'SECURITY',
                'MEAL',
                'GENERAL'
            )
        ),

    CONSTRAINT chk_notifications_priority
        CHECK (
            priority IN (
                'LOW',
                'NORMAL',
                'HIGH',
                'URGENT'
            )
        ),

    CONSTRAINT chk_notifications_channel
        CHECK (
            channel IN (
                'IN_APP',
                'PUSH',
                'EMAIL',
                'SMS',
                'MULTI_CHANNEL'
            )
        ),

    CONSTRAINT chk_notifications_status
        CHECK (
            status IN (
                'QUEUED',
                'SCHEDULED',
                'SENDING',
                'SENT',
                'PARTIALLY_DELIVERED',
                'FAILED',
                'CANCELLED',
                'EXPIRED'
            )
        ),

    CONSTRAINT chk_notifications_title
        CHECK (length(trim(title)) > 0),

    CONSTRAINT chk_notifications_message
        CHECK (length(trim(message)) > 0),

    CONSTRAINT chk_notifications_schedule
        CHECK (
            sent_at IS NULL
            OR scheduled_at IS NULL
            OR sent_at >= scheduled_at
        ),

    CONSTRAINT chk_notifications_expiry
        CHECK (
            expires_at IS NULL
            OR scheduled_at IS NULL
            OR expires_at >= scheduled_at
        )
);

COMMENT ON TABLE app.notifications IS
'Notifications generated by HMS modules and delivered to users.';

COMMENT ON COLUMN app.notifications.source_module IS
'Application module that generated the notification.';

COMMENT ON COLUMN app.notifications.source_record_id IS
'Optional business record that caused the notification.';


-- ============================================================================
-- 2. NOTIFICATION RECIPIENTS
-- ============================================================================
-- One row per recipient.
--
-- This table is intentionally separate from notifications because delivery
-- status can differ for every recipient.
-- ============================================================================

CREATE TABLE IF NOT EXISTS app.notification_recipients (
    id                  uuid PRIMARY KEY DEFAULT platform.generate_uuid(),

    notification_id     uuid NOT NULL,
    user_id             uuid,

    recipient_address   text,

    delivery_status     text NOT NULL DEFAULT 'PENDING',

    queued_at           timestamptz NOT NULL DEFAULT now(),
    sent_at             timestamptz,

    delivered_at        timestamptz,
    read_at             timestamptz,

    failed_at           timestamptz,

    failure_reason      text,

    device_token        text,

    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_notification_recipients_notification
        FOREIGN KEY (notification_id)
        REFERENCES app.notifications(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_notification_recipients_user
        FOREIGN KEY (user_id)
        REFERENCES app.users(user_id)
        ON DELETE SET NULL,

    CONSTRAINT chk_notification_recipients_status
        CHECK (
            delivery_status IN (
                'PENDING',
                'QUEUED',
                'SENT',
                'DELIVERED',
                'READ',
                'FAILED',
                'CANCELLED'
            )
        ),

    CONSTRAINT chk_notification_recipients_identity
        CHECK (
            user_id IS NOT NULL
            OR recipient_address IS NOT NULL
        ),

    CONSTRAINT chk_notification_recipients_delivery_time
        CHECK (
            delivered_at IS NULL
            OR sent_at IS NULL
            OR delivered_at >= sent_at
        ),

    CONSTRAINT chk_notification_recipients_read_time
        CHECK (
            read_at IS NULL
            OR delivered_at IS NULL
            OR read_at >= delivered_at
        ),

    CONSTRAINT chk_notification_recipients_failure_time
        CHECK (
            failed_at IS NULL
            OR sent_at IS NULL
            OR failed_at >= sent_at
        )
);

COMMENT ON TABLE app.notification_recipients IS
'Per-recipient notification delivery and read history.';

COMMENT ON COLUMN app.notification_recipients.delivery_status IS
'Delivery lifecycle for this specific recipient.';


