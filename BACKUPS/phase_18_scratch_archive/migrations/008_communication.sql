-- ============================================================================
-- 5. TENANT CONSISTENCY FOR NOTIFICATIONS
-- ============================================================================

CREATE OR REPLACE FUNCTION app.validate_communication_tenant_consistency()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    referenced_college_id uuid;
BEGIN

    -- ------------------------------------------------------------------------
    -- NOTIFICATION
    -- ------------------------------------------------------------------------

    IF TG_TABLE_NAME = 'notifications'
       AND NEW.college_id IS NOT NULL THEN

        SELECT c.id
        INTO referenced_college_id
        FROM platform.colleges c
        WHERE c.id = NEW.college_id;

        IF referenced_college_id IS NULL THEN
            RAISE EXCEPTION
                'College % does not exist',
                NEW.college_id;
        END IF;

    END IF;


    -- ------------------------------------------------------------------------
    -- ANNOUNCEMENT
    -- ------------------------------------------------------------------------

    IF TG_TABLE_NAME = 'announcements' THEN

        SELECT c.id
        INTO referenced_college_id
        FROM platform.colleges c
        WHERE c.id = NEW.college_id;

        IF referenced_college_id IS NULL THEN
            RAISE EXCEPTION
                'College % does not exist',
                NEW.college_id;
        END IF;

    END IF;


    RETURN NEW;
END;
$$;


-- ============================================================================
-- 6. COMMUNICATION TENANT TRIGGERS
-- ============================================================================

DROP TRIGGER IF EXISTS trg_notifications_tenant_consistency
ON app.notifications;

CREATE TRIGGER trg_notifications_tenant_consistency
BEFORE INSERT OR UPDATE
ON app.notifications
FOR EACH ROW
EXECUTE FUNCTION app.validate_communication_tenant_consistency();


